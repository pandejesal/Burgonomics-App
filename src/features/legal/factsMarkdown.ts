/**
 * Markdown for `LEGAL-FACTS-NEEDED.md` — the owner-facing list of facts the
 * legal pages are still waiting on.
 *
 * Why generate it instead of hand-writing it: the list, the `[[PLACEHOLDER:…]]`
 * tokens inside the documents, and the "printed but unverified" notices all
 * come from `./content/legalContent`. A hand-kept file drifts the moment
 * someone edits a page, and a stale list is how a statutory gap ships.
 *
 * `scripts/render-legal-facts.ts` writes the file; `tests/legal-pages.test.ts`
 * fails when the committed file is out of step with this output.
 */
import {
  LEGAL_DOCUMENTS,
  LEGAL_FACTS_TO_CONFIRM,
  LEGAL_PLACEHOLDERS,
  legalPublicPath,
} from "./content/legalContent";

/** Documents that mention a given placeholder token. */
function documentsUsing(id: string): string[] {
  const token = `[[PLACEHOLDER:${id}]]`;
  return LEGAL_DOCUMENTS.filter((document) => JSON.stringify(document).includes(token)).map(
    (document) => `\`${legalPublicPath(document.slug)}\``,
  );
}

export function renderLegalFactsMarkdown(): string {
  const missing = LEGAL_PLACEHOLDERS.map((placeholder, index) => {
    const used = documentsUsing(placeholder.id);
    return [
      `### M${index + 1}. ${placeholder.label}`,
      "",
      `- **Marked on:** ${
        used.length > 0
          ? used.join(", ")
          : "**NOT RENDERED — the token is missing from every document**"
      }`,
      `- **Token id:** \`${placeholder.id}\``,
      `- **Who supplies it:** ${placeholder.owner}`,
      `- **Why it is needed:** ${placeholder.why}`,
      `- **Where it lands in code:** ${placeholder.codeLocation}`,
      `- **Done when:** ${placeholder.doneWhen}`,
      "",
    ].join("\n");
  }).join("\n");

  const confirm = LEGAL_FACTS_TO_CONFIRM.map((fact, index) =>
    [
      `### C${index + 1}. ${fact.label} — printed today as: ${fact.currentValue}`,
      "",
      `- **Token id:** \`${fact.id}\``,
      `- **Who confirms it:** ${fact.owner}`,
      `- **Why it is needed:** ${fact.why}`,
      `- **Where it lands in code:** ${fact.codeLocation}`,
      `- **Done when:** ${fact.doneWhen}`,
      "",
    ].join("\n"),
  ).join("\n");

  return `<!-- GENERATED by scripts/render-legal-facts.ts — do not edit by hand. -->
<!-- Regenerate: npm run legal:facts -->

# Legal facts the app is still waiting on

The customer app ships four legal pages: Privacy Policy, Terms of Use, Refund & Cancellation
Policy, and Grievance Redressal. They are reachable in the app (Profile → More, plus terms and
privacy on the sign-in screen) and published as static HTML at \`/legal/<slug>\` on the Customer
app's own hosting — not \`burgonomics.com\`, which is out of scope for this wave — so a store
listing can point at a real URL.

Two things must be true before those pages go to a store:

1. **No page may still show a \`[TO BE SUPPLIED: …]\` mark.** Those marks are facts only the owner
   can supply, listed below as **M1-M${LEGAL_PLACEHOLDERS.length}**. While any mark is on a page,
   the page itself says so in a banner and **the release checklist blocks**.
2. **Every fact printed but never verified must be confirmed** — listed below as
   **C1-C${LEGAL_FACTS_TO_CONFIRM.length}**. Those print as ordinary values, so a wrong one is
   silent, which is exactly why they block the release too.

Both lists are generated from
\`burgonomics-foundation-core/src/features/legal/content/legalContent.ts\`
(\`LEGAL_PLACEHOLDERS\` and \`LEGAL_FACTS_TO_CONFIRM\`), the same module that renders the pages, so
the copy a customer reads and the list the owner works from cannot drift apart.

**Status today: ${LEGAL_PLACEHOLDERS.length} facts missing, ${LEGAL_FACTS_TO_CONFIRM.length} facts unverified.**
This is not a prediction: the pages currently render those marks, and \`tests/legal-pages.test.ts\`
pins that they do.

---

## Part 1 — missing facts (rendered as \`[TO BE SUPPLIED: …]\`)

${missing}
---

## Part 2 — printed but unverified (no mark on the page, still blocking)

${confirm}
---

## What the release worker must do with this file

- Mirror both lists into the release checklist at
  \`client-handover/STORE_SUBMISSION_CHECKLIST.md\` (section "Legal facts — BLOCKING"). That section
  already exists; keep it in step.
- Do **not** submit either app to Google Play or the App Store while Part 1 is non-empty. A legal
  page carrying a visible placeholder is a rejection risk and, worse, an unenforceable disclosure.
- Do **not** treat Part 1 as engineering's job. The FSSAI licences, the Grievance Officer's name
  and phone, the CIN question and the mailbox confirmations all need the owner.

## How to verify the pages are clean

\`\`\`bash
cd burgonomics-foundation-core
npm run legal:facts -- --check   # this file is in step with the content module
npm run legal:html               # regenerate the four published HTML pages
npm test -- tests/legal-pages.test.ts
\`\`\`

Expected once every fact is in: \`privacy 0  terms 0  refund-policy 0  grievance 0\` missing
\`[TO BE SUPPLIED:\` marks, and no "not publishable yet" banner on any page.
`;
}
