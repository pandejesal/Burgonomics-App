export function customizationsFor(productId: string): CustomizationGroup[] {
  const product = SAMPLE_PRODUCTS.find((p) => p.id === productId);
  if (!product?.customizable) return [];

  // Burger Categories
  if (
    product.categoryId === "cat_classic_burgers" ||
    product.categoryId === "cat_big_bang_burgers" ||
    product.categoryId === "cat_sizzling_burgers"
  ) {
    return [GRP_SPICE_LEVEL, GRP_BURGER_ADDONS];
  }

  // Coffee Category
  if (product.categoryId === "cat_beverages" && product.name.toLowerCase().includes("coffee")) {
    return [GRP_COFFEE_ADDONS];
  }

  return [];
}

// ---------- Details ----------------------------------------------------

export function detailsFor(productId: string): ProductDetails | null {
  const base = SAMPLE_PRODUCTS.find((p) => p.id === productId);
  if (!base) return null;

  let ingredients: string[] | undefined;
  let nutrition: { key: string; label: string; value: string }[] | undefined;

  if (
    base.categoryId === "cat_classic_burgers" ||
    base.categoryId === "cat_big_bang_burgers" ||
    base.categoryId === "cat_sizzling_burgers"
  ) {
    ingredients = [
      "Signature soft brioche sesame bun",
      "Fresh crisp iceberg lettuce",
      "Sliced onions & juicy tomatoes",
      "House special Burgonomics sauce",
    ];
    if (base.name.toLowerCase().includes("paneer")) {
      ingredients.push("Premium fresh marinated Paneer patty");
    } else if (base.name.toLowerCase().includes("cheese")) {
      ingredients.push("Molten cheddar cheese cheese-burst patty");
    } else {
      ingredients.push("Crispy double-cooked potato and vegetable patty");
    }

    nutrition = [
      {
        key: "cal",
        label: "Calories",
        value: base.categoryId === "cat_big_bang_burgers" ? "610 kcal" : "480 kcal",
      },
      {
        key: "pro",
        label: "Protein",
        value: base.name.toLowerCase().includes("paneer") ? "19 g" : "11 g",
      },
      {
        key: "fat",
        label: "Fat",
        value: base.name.toLowerCase().includes("cheese") ? "28 g" : "18 g",
      },
    ];
  } else if (base.categoryId === "cat_pizza") {
    ingredients = [
      "Fresh hand-stretched dough",
      "Traditional pizza marinara sauce",
      "Gooey mozzarella cheese blend",
    ];
    nutrition = [
      { key: "cal", label: "Calories", value: "720 kcal" },
      { key: "pro", label: "Protein", value: "24 g" },
      { key: "fat", label: "Fat", value: "21 g" },
    ];
  }

  return {
    ...base,
    ingredients,
    nutrition,
    customizations: customizationsFor(productId),
    allowSpecialInstructions: true,
  };
}
